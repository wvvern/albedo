package dev.albedo.core.ui;

/**
 * The keys the settings screen reacts to; adapters translate their version's key events into these, and find the
 * select-all and paste shortcuts with their version's own rules.
 */
public enum UiKey {
    BACKSPACE, DELETE, LEFT, RIGHT, UP, DOWN, HOME, END, ENTER, ESCAPE, TAB, SELECT_ALL, PASTE
}
